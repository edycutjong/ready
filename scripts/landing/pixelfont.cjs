  /* SVG path data for one line of text: horizontal runs merged per glyph row. (x,y) = top-left, px = cell size. */
  function path(text, x, y, px) {
    let d = '';
    [...String(text).toUpperCase()].forEach((ch, i) => {
      rows(ch).forEach((row, r) => {
        let c = 0;
        while (c < 8) {
          if (row[c] !== '#') { c++; continue; }
          let e = c; while (e < 8 && row[e] === '#') e++;
          const X = +(x + (i * 8 + c) * px).toFixed(2), Y = +(y + r * px).toFixed(2), W = +((e - c) * px).toFixed(2);
          d += `M${X} ${Y}h${W}v${+px.toFixed(2)}h-${W}z`;
          c = e;
        }
      });
    });
    return d;
  }
